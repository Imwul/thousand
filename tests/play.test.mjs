  const ids=PROCEDURE_GROUPS.flatMap(group=>group.ids);
  assert.equal(ids.length,PROCEDURES.length);
  assert.deepEqual(new Set(ids),new Set(PROCEDURES.map(procedure=>procedure.id)));
